CREATE TABLE users (
 user_id BIGINT PRIMARY KEY,
 email VARCHAR(254) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
 password_hash VARCHAR(100) NOT NULL,
 nickname VARCHAR(64) NOT NULL,
 bio VARCHAR(1000) NULL,
 avatar_key VARCHAR(255) NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 auth_version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 CONSTRAINT uk_users_email UNIQUE(email),
 CONSTRAINT ck_user_status CHECK (status IN ('ACTIVE','DISABLED'))
);
CREATE TABLE user_roles (
 user_id BIGINT NOT NULL,
 role VARCHAR(16) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 PRIMARY KEY(user_id,role),
 CONSTRAINT fk_role_user FOREIGN KEY(user_id) REFERENCES users(user_id),
 CONSTRAINT ck_role CHECK (role IN ('BUYER','CREATOR'))
);
CREATE TABLE creator_profiles (
 creator_id BIGINT PRIMARY KEY,
 user_id BIGINT NOT NULL,
 display_name VARCHAR(64) NOT NULL,
 bio VARCHAR(1000) NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 CONSTRAINT uk_creator_user UNIQUE(user_id),
 CONSTRAINT fk_creator_user FOREIGN KEY(user_id) REFERENCES users(user_id),
 CONSTRAINT ck_creator_status CHECK (status IN ('ACTIVE','DISABLED'))
);
